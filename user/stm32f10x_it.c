/* ============================================================================
 * stm32f10x_it.c —— 系统中断服务（全部收口在这里）
 * ----------------------------------------------------------------------------
 * 工程里所有中断函数集中放这一个文件，是"企业级"目录规范。
 * 每个 ISR 的职责都在它调用的那个回调里实现：
 *   SysTick        → 毫秒时钟（Delay）
 *   USART1         → 串口接收进环形缓冲
 *   EXTI1/EXTI15_10→ 按键唤醒标记
 * 关于"ISR 要短"：这里每个函数都只干一件事，其余逻辑全在模块里。
 * ========================================================================== */
#include "stm32f10x_it.h"
#include "Delay.h"
#include "USART.h"
#include "Key.h"

/* ----------------------------------------------------------------
 * 系统异常（不期望发生；真来了基本说明程序写坏了，让 CPU 停住好排查）
 * 模板本来就有这几个名字，替换文件时保持同名即可。
 * ---------------------------------------------------------------- */
void NMI_Handler(void)                { while (1); }
void HardFault_Handler(void)          { while (1); }
void MemManage_Handler(void)          { while (1); }
void BusFault_Handler(void)           { while (1); }
void UsageFault_Handler(void)         { while (1); }
void SVC_Handler(void)                { }
void DebugMon_Handler(void)           { }
void PendSV_Handler(void)             { }

/* ----------------------------------------------------------------
 * SysTick：1ms 的系统节拍 → 毫秒时钟 +1（全工程时间的源头）
 * ---------------------------------------------------------------- */
void SysTick_Handler(void)
{
    Delay_TickISR();
}

/* ----------------------------------------------------------------
 * USART1：每收 1 字节进中断，丢给串口模块塞进环形缓冲
 *   RXNE 标志在读 DR(USART_ReceiveData) 时自动清除——不用手动清
 * ---------------------------------------------------------------- */
void USART1_IRQHandler(void)
{
    USART_RxISR();
}

/* ----------------------------------------------------------------
 * EXTI 线 1：KEY1(PB1) 唤醒
 *   Sleep/Stop 模式下系统从这醒来；ISR 只置唤醒标志
 * ---------------------------------------------------------------- */
void EXTI1_IRQHandler(void)
{
    Key_Wake_ISR(EXTI_Line1);
}

/* ----------------------------------------------------------------
 * EXTI 线 11~15 共用这一个函数：KEY2(PB11) 在 11 号线上
 *   必须在函数里再查一次标志，确认是"我的线"响
 * ---------------------------------------------------------------- */
void EXTI15_10_IRQHandler(void)
{
    /* 本工程只用 11 号线；查询并交给按键模块(它会清标志) */
    if (EXTI_GetITStatus(EXTI_Line11) == SET)
    {
        Key_Wake_ISR(EXTI_Line11);
    }
}