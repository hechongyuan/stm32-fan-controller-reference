#ifndef __APP_PROTOCOL_H
#define __APP_PROTOCOL_H

#include "stm32f10x.h"

/* ============ 上行上报数据帧（本项目自定义协议） ============
 * 帧格式：
 *   [0] 0xAA        帧头1
 *   [1] 0x55        帧头2
 *   [2] len         数据段长度
 *   [3] ...         数据段（下面是上报内容的布局）
 *   [N] CRC8        整帧校验（从 len 字节算到末尾）
 *
 * 上报帧数据段布局（len=6）：
 *   [0] 运行状态   0=关机 1=运行
 *   [1] 档位       0~100
 *   [2..3] 温度×10   高字节在前
 *   [4..5] 湿度×10   高字节在前
 *
 * 附加：串口还能收"控制指令帧"（同协议，数据段 [0]=命令码）：
 *   [0]=0x01 → 设置档位，[1]=目标档位
 *   [0]=0x02 → 开关机，[1]=0 关 / 1 开
 * ============================================================ */

void AppProtocol_Init(void);          /* 初始化：构建 CRC8 查表 */
void AppProtocol_Tick(void);          /* main 每 1 秒调：组一帧并发送 */
void AppProtocol_Process(void);       /* 主循环每次调：解析串口收到的控制帧 */

#endif