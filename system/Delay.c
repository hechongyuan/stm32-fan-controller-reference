/* ============================================================================
 * Delay.c —— 系统时钟与延时
 * ----------------------------------------------------------------------------
 * 设计思想：整个工程"时间"都要有唯一来源。这里用 SysTick 做一个 1ms 的
 * 硬件中断节奏，中断里给全局毫秒计数器 G_ms 加 1。全工程所有"什么时刻"、
 * "过了多久"的问题都看 G_GetMs()：延时、分频调度、超时判断全部基于它。
 *
 * 为什么不像新手那样用一个空转小循环当延时？
 *   空转延时(while 循环减计数)会随系统主频、优化等级变化，也不占"真实
 *   时钟基准"。用 SysTick 中断，时间永远是准确、可对外的。
 * ========================================================================== */
#include "Delay.h"

volatile uint32_t g_ms_count = 0;   /* 全局毫秒计数器：中断里 +1，主程序里读 */

/* SysTick 中断服务（在 stm32f10x_it.c 里被调用，别在这里写 Keil 专属函数名） */
void Delay_TickISR(void)
{
    g_ms_count++;                    /* 每 1ms 加一次 */
}

/* 初始化：把 SysTick 配成 1ms 中断（SystemCoreClock 来自 system_stm32f10x） */
void Delay_Init(void)
{
    /* SysTick 时钟源选 HCLK，重装值 = 主频/1000 → 每 1ms 计满一次进中断 */
    if (SysTick_Config(SystemCoreClock / 1000) == 1)
    {
        while (1);                   /* 配置失败直接停（几乎不会发生） */
    }
}

/* 读取当前毫秒时钟 */
uint32_t G_GetMs(void)
{
    return g_ms_count;
}

/* 毫秒延时：读取基准时刻，轮询"当前 - 基准"直到到点
 * 用 uint32 无符号减法：计数器绕回 0 时依然算得对（之前讲过的环形计时技巧） */
void Delay_ms(uint32_t ms)
{
    uint32_t start = g_ms_count;     /* 记录出发时刻 */
    while (g_ms_count - start < ms)  /* 未到点就继续等 */
    {
        /* 这里空着：期间可被其他中断打断（比如按键 EXTI、串口），不影响计时 */
    }
}